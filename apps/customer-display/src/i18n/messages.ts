export type MsgKey = keyof typeof EN;


// POSLanguage.pdf §16 / Appendix A §117 (Oct 28 2026): the Customer Display is ENGLISH ONLY — even beside a Vietnamese POS
// in the same session. Its optional Vietnamese (and the guest's switch) were removed; only the Front Desk POS is bilingual.
// Guest / salon / service names are business data and are shown exactly as saved (Vietnamese included).
export const DISPLAY_LANGUAGES = ['en'] as const;
export type DisplayLanguage = (typeof DISPLAY_LANGUAGES)[number];
export const CATALOGS: Record<DisplayLanguage, Record<MsgKey, string>> = { en: EN };
/** Each language's own name, shown on the switch in that language. */
export const LANGUAGE_NAMES: Record<DisplayLanguage, string> = { en: 'English' };
/** The locale for dates and numbers. */
export const LOCALES: Record<DisplayLanguage, string> = { en: 'en-US' };

/** One message, placeholders filled. An unknown language falls back to English. */
export function translate(lang: string, key: MsgKey, vars: Record<string, string | number> = {}): string {
  const cat = (CATALOGS as Record<string, Record<MsgKey, string>>)[lang] ?? EN;
  return (cat[key] ?? EN[key]).replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
