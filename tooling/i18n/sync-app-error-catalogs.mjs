#!/usr/bin/env node
// sync-app-error-catalogs.mjs — Vietnamese POS §2 / §21 / §58 (V-5, Oct 27 2026; English only since POSLanguage.pdf, Oct 28): the Owner App and the Tech App word a
// server refusal from the SAME code → text mapping as the POS. The source is the POS errors namespace
// (apps/pos-web/src/i18n/ns/errors.{en,vi}.ts — reviewed by Kevin in docs/i18n/VI_NEW_STRINGS_FOR_REVIEW.md); each app gets
// its own generated catalogue (apps/{owner,tech}-web/src/i18n/errors.generated.ts) with every `errors.<CODE>` key (the
// registry codes — not the POS-only client fallbacks, deal reasons or field / rule words), registered at import time and
// used by the mobile transport (packages/mobile-sdk i18n/error-message.ts).
//   node tooling/i18n/sync-app-error-catalogs.mjs           rewrite both files
//   node tooling/i18n/sync-app-error-catalogs.mjs --check   exit 1 when a file is out of date (run by check-error-text)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const ROOT = new URL('../../', import.meta.url).pathname;
const NS = ROOT + 'apps/pos-web/src/i18n/ns/';

function tsObject(src, name) {
  const start = src.search(new RegExp(`export const ${name}\\b[^=]*=\\s*\\{`));
  if (start < 0) throw new Error(`no ${name}`);
  let i = src.indexOf('{', start), depth = 0, j = i;
  for (; j < src.length; j++) { if (src[j] === '{') depth++; else if (src[j] === '}' && --depth === 0) break; }
  const out = []; const re = /(['"])((?:\\.|(?!\1).)*)\1\s*:\s*(['"`])((?:\\.|(?!\3)[\s\S])*)\3/g; let m;
  const body = src.slice(i + 1, j);
  while ((m = re.exec(body))) out.push([m[2], m[4]]);
  return out;
}
const pick = (pairs) => pairs.filter(([k]) => /^errors\.[A-Z][A-Z0-9_]*$/.test(k));
const EN = pick(tsObject(readFileSync(NS + 'errors.en.ts', 'utf8'), 'ERRORS_EN'));

export function render(prefix) {
  const line = ([k, v]) => `  '${k}': '${v}',`;   // values are copied as written in the POS files (already escaped there)
  return `// errors.generated.ts — GENERATED by tooling/i18n/sync-app-error-catalogs.mjs from the POS errors namespace
// (apps/pos-web/src/i18n/ns/errors.en.ts). Do not edit: change the POS file and re-run the script. V-5 (Oct 27 2026):
// a server refusal is worded from its registry code (details.messageCode / code) — the same English the POS shows.
// ENGLISH ONLY (POSLanguage.pdf §1 / §22, Oct 28 2026): only the Front Desk POS is bilingual. ${EN.length} codes.
import { registerCatalog } from '@aipowersalon/mobile-sdk/i18n';

export const ${prefix}_ERRORS_EN: Record<string, string> = {
${EN.map(line).join('\n')}
};
registerCatalog('en', ${prefix}_ERRORS_EN);
`;
}
const TARGETS = [['owner-web', 'OWNER'], ['tech-web', 'TECH']];
const check = process.argv.includes('--check');
let stale = 0;
for (const [app, prefix] of TARGETS) {
  const p = `${ROOT}apps/${app}/src/i18n/errors.generated.ts`;
  const want = render(prefix);
  if (check) { if (!existsSync(p) || readFileSync(p, 'utf8') !== want) { console.log(`out of date: apps/${app}/src/i18n/errors.generated.ts — run node tooling/i18n/sync-app-error-catalogs.mjs`); stale++; } }
  else writeFileSync(p, want);
}
if (check && stale) process.exit(1);
if (!check) console.log(`wrote ${TARGETS.length} app error catalogues (${EN.length} codes)`);
