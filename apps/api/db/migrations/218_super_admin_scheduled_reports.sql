-- 173_super_admin_scheduled_reports.sql — Platform (Super Admin) scheduled reports + their run history.
-- A schedule periodically generates an export artifact and records a run. Generation reuses the existing
-- analytics export (analytics_export) or a saved report definition (saved_report) — no new aggregation here.
--
-- Honest design notes (reflected in the API + UI):
--   * There is no in-process cron in this codebase. Schedules become "due" by next_run_at and are executed when an
--     external scheduler calls POST /super-admin/scheduled-reports/run-due (idempotent: each run advances next_run_at).
--   * There is no mailer wired. recipients_json stores intended email recipients, but actual delivery is IN-APP:
--     the run row holds the artifact for download. delivery_method is constrained to 'in_app' until a mailer exists.
--   * Money/tenant data are never stored here — only the report *selection* and the generated artifact bytes.

CREATE TABLE IF NOT EXISTS super_admin_scheduled_reports (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name                  TEXT NOT NULL,
  source                TEXT NOT NULL DEFAULT 'analytics_export', -- analytics_export | saved_report
  report_definition_id  UUID,                                     -- → super_admin_report_definitions.id (saved_report)
  format                TEXT NOT NULL DEFAULT 'csv',              -- csv | xlsx | pdf
  range_key             TEXT NOT NULL DEFAULT '30d',              -- 7d | 30d | 90d | 6m | 12m
  scope_tenant_id       UUID,                                     -- NULL = platform-wide
  frequency             TEXT NOT NULL DEFAULT 'weekly',           -- daily | weekly | monthly
  recipients_json       JSONB NOT NULL DEFAULT '[]'::jsonb,       -- intended email recipients (delivery pending mailer)
  delivery_method       TEXT NOT NULL DEFAULT 'in_app',          -- in_app (only wired method today)
  enabled               BOOLEAN NOT NULL DEFAULT true,
  next_run_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_run_at           TIMESTAMPTZ,
  created_by_user_id    UUID,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT sa_scheduled_reports_source_chk    CHECK (source IN ('analytics_export','saved_report')),
  CONSTRAINT sa_scheduled_reports_format_chk    CHECK (format IN ('csv','xlsx','pdf')),
  CONSTRAINT sa_scheduled_reports_range_chk     CHECK (range_key IN ('7d','30d','90d','6m','12m')),
  CONSTRAINT sa_scheduled_reports_freq_chk      CHECK (frequency IN ('daily','weekly','monthly')),
  CONSTRAINT sa_scheduled_reports_delivery_chk  CHECK (delivery_method IN ('in_app'))
);
CREATE INDEX IF NOT EXISTS sa_scheduled_reports_due ON super_admin_scheduled_reports (next_run_at) WHERE enabled;

CREATE TABLE IF NOT EXISTS super_admin_scheduled_report_runs (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  schedule_id           UUID NOT NULL,
  status                TEXT NOT NULL,                            -- success | error
  format                TEXT NOT NULL,
  filename              TEXT,
  artifact_base64       TEXT,                                     -- the generated bytes (in-app download); NULL on error
  byte_size             INTEGER NOT NULL DEFAULT 0,
  error                 TEXT,
  trigger              TEXT NOT NULL DEFAULT 'run_due',           -- run_due | manual
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT sa_scheduled_report_runs_status_chk CHECK (status IN ('success','error'))
);
CREATE INDEX IF NOT EXISTS sa_scheduled_report_runs_schedule ON super_admin_scheduled_report_runs (schedule_id, created_at DESC);
