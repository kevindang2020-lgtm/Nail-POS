#!/usr/bin/env node
// changed-paths.mjs — Security Deep Scan §180: the exact created / modified / deleted / renamed paths of every security
// commit, generated from git (never typed by hand). A security commit = one named in docs/security/SECURITY_FIX_REGISTER.md
// (its "Commit" column) or one whose subject starts with `security(` or names the Security Deep Scan.
//   node tooling/security/changed-paths.mjs            write docs/security/SECURITY_CHANGED_PATHS.md
//   node tooling/security/changed-paths.mjs --check    exit 1 when the file is out of date
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = join(ROOT, 'docs/security/SECURITY_CHANGED_PATHS.md');
const git = (...a) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });

const register = readFileSync(join(ROOT, 'docs/security/SECURITY_FIX_REGISTER.md'), 'utf8');
const named = new Set([...register.matchAll(/\b([0-9a-f]{8})\b/g)].map((m) => m[1]));
const log = git('log', '--format=%H%x09%h%x09%ad%x09%s', '--date=short', '--since=2026-10-22').trim().split('\n').filter(Boolean);
const commits = [];
for (const line of log) {
  const [full, short, date, subject] = line.split('\t');
  const isSec = named.has(short) || named.has(full.slice(0, 8)) || /^security\(|Security Deep Scan/i.test(subject);
  if (isSec) commits.push({ full, short: full.slice(0, 8), date, subject });
}
for (const h of named) if (!commits.some((c) => c.short === h)) {
  try { const [full, date, subject] = git('show', '-s', '--format=%H%x09%ad%x09%s', '--date=short', h).trim().split('\t'); commits.push({ full, short: full.slice(0, 8), date, subject }); } catch { /* a hash in prose that is not a commit here */ }
}
commits.sort((a, b) => (a.date === b.date ? 0 : a.date < b.date ? 1 : -1));
const KIND = { A: 'created', M: 'modified', D: 'deleted', R: 'renamed', C: 'copied', T: 'type changed' };
const parts = ['# Security changed paths (Security Deep Scan §180)', '',
  'GENERATED by `node tooling/security/changed-paths.mjs` from git — the exact paths each security commit created, modified, renamed or',
  'deleted (deprecated code is removed, so it appears as deleted). Security commits: those named in `SECURITY_FIX_REGISTER.md` and those',
  'whose subject starts with `security(` or names the Security Deep Scan. Do not edit by hand.', ''];
const totals = { created: 0, modified: 0, deleted: 0, renamed: 0 };
for (const c of commits) {
  const rows = git('show', '--format=', '--name-status', '-M', c.full).trim().split('\n').filter(Boolean).map((l) => l.split('\t'));
  parts.push(`## ${c.short} · ${c.date} · ${c.subject.replace(/\|/g, '/').slice(0, 160)}`, '');
  parts.push('| change | path |', '|---|---|');
  for (const r of rows) {
    const k = KIND[r[0][0]] ?? r[0];
    if (k in totals) totals[k]++;
    parts.push(`| ${k} | \`${r.length > 2 ? `${r[1]} → ${r[2]}` : r[1]}\` |`);
  }
  parts.push('');
}
parts.splice(6, 0, `${commits.length} commits · ${totals.created} paths created · ${totals.modified} modified · ${totals.renamed} renamed · ${totals.deleted} deleted`, '');
const text = parts.join('\n') + '\n';
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.log('SECURITY_CHANGED_PATHS.md is out of date — run node tooling/security/changed-paths.mjs'); process.exit(1); }
  console.log('SECURITY_CHANGED_PATHS.md current'); process.exit(0);
}
writeFileSync(OUT, text);
console.log(`wrote ${OUT.replace(ROOT + '/', '')}: ${commits.length} commits`);
