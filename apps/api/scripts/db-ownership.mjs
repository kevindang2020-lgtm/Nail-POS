#!/usr/bin/env node
// db-ownership.mjs — BUILD_PLAN Phase 10 (Constitution 1 §3, §7, §105): the table ownership registry.
//
//   node scripts/db-ownership.mjs --write   regenerate apps/api/db/ownership/registry.generated.json from the real schema
//   node scripts/db-ownership.mjs --check   (gate `check:db-ownership`) regenerate in memory and FAIL when
//       * a table has no ownership class or domain (heuristics could not decide and overrides.json has no entry),
//       * a tenant_owned / tenant_branch_owned table has no tenant_id, a tenant_branch_owned one no branch_id,
//         a platform_global one HAS tenant_id,
//       * an override names a table that no longer exists or has no reason,
//       * the committed registry differs from the schema (a new table, a dropped one, a changed column fact) — run --write
//         and commit the diff with the migration.
//
// The schema comes from every migration replayed into PGlite (packages/testing's cached harness), so the registry is the
// schema the code will run against, not a hand list. Hand decisions live in overrides.json, each with a reason.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { migratedPglite } from '../../../packages/testing/src/pgtest-schema.mjs';
import { introspect, buildRegistry, ruleViolations, registryDrift, summarise } from '../db/ownership/registry.mjs';

const API = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(API, 'db', 'ownership');
const REG = join(DIR, 'registry.generated.json');
const readJson = (p, d) => (existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : d);
const mode = process.argv.includes('--write') ? 'write' : 'check';

const overrides = readJson(join(DIR, 'overrides.json'), { tables: {} });
const retention = readJson(join(API, 'db', 'retention-policy.json'), { tables: {} });
const pg = await migratedPglite();
const fresh = buildRegistry(await introspect(pg), overrides, retention);
await pg.close?.();
const rules = ruleViolations(fresh, overrides);
const sum = summarise(fresh);

if (mode === 'write') {
  const doc = {
    $comment: 'GENERATED by apps/api/scripts/db-ownership.mjs --write from the migrated schema — do not hand-edit; put decisions in overrides.json. Constitution 1 §3 (ownership A–E), §7 (domain), sensitivity (classify-schema classes), retention_class / delete_policy from db/retention-policy.json.',
    classes: { A: 'platform_global', B: 'tenant_owned', C: 'tenant_branch_owned', D: 'platform_identity_tenant_relationship', E: 'cross_tenant_platform_data' },
    summary: sum,
    tables: fresh,
  };
  writeFileSync(REG, JSON.stringify(doc, null, 1) + '\n');
  console.log(`db-ownership: wrote ${sum.tables} tables → ${REG.replace(API + '/', 'apps/api/')}`);
  if (rules.length) { console.log(`db-ownership: ${rules.length} rule violation(s):\n  ` + rules.join('\n  ')); process.exit(1); }
  process.exit(0);
}

const committed = readJson(REG, null)?.tables;
const drift = committed ? registryDrift(committed, fresh) : ['registry.generated.json is missing — run node scripts/db-ownership.mjs --write'];
const errs = [...rules, ...drift];
if (errs.length) {
  console.error(`❌ db-ownership: ${errs.length} problem(s)` + (drift.length ? ' — after fixing overrides, run `node scripts/db-ownership.mjs --write` and commit the registry' : ''));
  for (const e of errs.slice(0, 60)) console.error('  ' + e);
  if (errs.length > 60) console.error(`  … and ${errs.length - 60} more`);
  process.exit(1);
}
console.log(`✅ db-ownership: ${sum.tables} tables classified (${Object.entries(sum.ownership).map(([k, v]) => `${k} ${v}`).join(', ')}); registry matches the schema.`);
process.exit(0);
