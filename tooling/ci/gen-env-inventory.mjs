#!/usr/bin/env node
// gen-env-inventory.mjs — writes ENV_INVENTORY.md: every environment variable NAME the backend and the apps read, who
// reads it, and whether production refuses to start without it (handoff mandate §135, Oct 22 2026). NAMES ONLY — this
// script never reads a value, and the output must never carry one.
//
//   node tooling/ci/gen-env-inventory.mjs            (re-run after adding a variable; the file is generated)
//
// "Blocks production startup" = the name appears in the production start check (apps/api/src/common/production-config.ts)
// or a helper it calls; everything else degrades to an honest "not configured" for its feature (or is a tuning knob).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SKIP = new Set(['node_modules', 'dist', 'coverage', '.vite', 'www']);
const walk = (d, out = []) => {
  for (const n of readdirSync(d)) {
    if (SKIP.has(n)) continue;
    const p = join(d, n); const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (/\.(ts|tsx|mjs)$/.test(n) && !/\.(test|spec)\.|vitest\.spec|pgtest|postgres-race/.test(n)) out.push(p);
  }
  return out;
};
const roots = ['apps', 'modules', 'packages'].map((r) => join(ROOT, r));
const files = roots.flatMap((r) => walk(r)).filter((f) => !/\/scripts\//.test(f) || /apps\/api\/scripts\/(migrate|seed)/.test(f));
const NAME = /process\.env\.([A-Z][A-Z0-9_]+)|process\.env\[['"]([A-Z][A-Z0-9_]+)['"]\]|import\.meta\.env\.([A-Z][A-Z0-9_]+)|\benv\.([A-Z][A-Z0-9_]{3,})\b/g;
const byName = new Map();
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  for (const m of src.matchAll(NAME)) {
    const n = m[1] || m[2] || m[3] || m[4];
    if (!n || ['NODE_OPTIONS'].includes(n)) continue;
    const rel = relative(ROOT, f);
    const owner = rel.split('/').slice(0, 2).join('/');
    if (!byName.has(n)) byName.set(n, new Set());
    byName.get(n).add(owner);
  }
}
// the start check itself and the exact helper functions it calls (their bodies + the top-level constants they name)
const fnBody = (src, name) => {
  const i = src.search(new RegExp(`export (async )?function ${name}\\b`)); if (i < 0) return '';
  const rest = src.slice(i); const end = rest.search(/\n}\n/); return end < 0 ? rest : rest.slice(0, end + 2);
};
const withConsts = (src, body) => body + [...new Set(body.match(/\b[A-Z][A-Z0-9_]{3,}\b/g) || [])]
  .map((c) => { const m = new RegExp(`\\n(?:export )?const ${c}\\b[\\s\\S]*?;\\n`).exec(src); return m ? m[0] : ''; }).join('');
const PARTS = [['apps/api/src/common/production-config.ts', ['productionConfigProblems', 'multiProcessReasons']], ['apps/api/src/common/key-ring.ts', ['missingProductionKeys']],
  ['modules/checkout/src/mobile-checkout/ttp-config.ts', ['tapToPayProductionProblems']], ['packages/media/src/media-storage.ts', ['mediaStorageConfigErrors']],
  ['modules/payments/src/payments/integrations-production-config.ts', ['integrationsProductionProblems']], ['packages/notifications/src/sender-selection.ts', ['messagingProductionProblems']]];
const START_CHECK = PARTS.map(([p, fns]) => { const src = readFileSync(join(ROOT, p), 'utf8'); return fns.map((f) => withConsts(src, fnBody(src, f))).join('\n'); }).join('\n');
const example = (() => { try { return readFileSync(join(ROOT, '.env.example'), 'utf8'); } catch { return ''; } })();
const secretsDoc = (() => { try { return readFileSync(join(ROOT, 'SECRETS_REQUIRED.md'), 'utf8'); } catch { return ''; } })();
const isSecretName = (n) => /SECRET|TOKEN|PASSWORD|PRIVATE|_KEY$|_KEY_|CREDENTIAL|SERVICE_ACCOUNT|DSN/.test(n);
// a name the start check only uses to recognise the mode (not a requirement): noted, not counted as "required"
const MODE = new Set(['NODE_ENV', 'API_REPLICAS', 'MULTI_INSTANCE', 'PROCESS_ROLE']);
const rows = [...byName.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([n, owners]) => {
  const inCheck = new RegExp(`\\b${n}\\b`).test(START_CHECK);
  const blocks = MODE.has(n) ? 'mode switch' : inCheck ? '**checked at start** (may be conditional)' : 'no — feature degrades / tuning';
  const front = [...owners].every((o) => o.startsWith('apps/') && o !== 'apps/api');
  return `| \`${n}\` | ${[...owners].sort().join(', ')} | ${front ? 'build-time (Vite)' : 'runtime'} | ${blocks} | ${isSecretName(n) ? 'secret' : '—'} | ${new RegExp(`^#?\\s*${n}=`, 'm').test(example) ? 'yes' : 'no'} | ${secretsDoc.includes(n) ? 'yes' : '—'} |`;
});
const out = `# ENV_INVENTORY.md — every environment variable NAME the code reads (generated)

Generated by \`node tooling/ci/gen-env-inventory.mjs\` — do not edit by hand; re-run it after adding a variable. **Names
only: no value is ever read or written here.** Values: \`.env.example\` (development defaults, no real secrets),
\`.env.production.example\` (shape), \`SECRETS_REQUIRED.md\` (who provides each secret). A row "checked at start" is read by
the production start check (\`apps/api/src/common/production-config.ts\` and the helpers it calls) — some are required
outright (\`DATABASE_URL\`, \`AUTH_SESSION_SECRET\`, the per-purpose encryption keys), others only in a mode (\`REDIS_URL\`
with more than one process; the bucket settings when \`MEDIA_STORE=s3\`; the Tap to Pay set when it is switched on) —
read the check for the exact condition. Every other row turns its feature off honestly ("not configured") or is a
tuning knob with a default. Test-only and proof-script variables are not listed.

${rows.length} names.

| Name | Read by | Kind | Blocks production startup | Sensitive | In .env.example | In SECRETS_REQUIRED.md |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(join(ROOT, 'ENV_INVENTORY.md'), out);
console.log(`ENV_INVENTORY.md: ${rows.length} names`);
