export const DISPLAY_LANGUAGES = ['en', 'vi'] as const;
export type DisplayLanguage = (typeof DISPLAY_LANGUAGES)[number];
export const CATALOGS: Record<DisplayLanguage, Record<MsgKey, string>> = { en: EN, vi: VI };
/** Each language's own name, shown on the switch in that language. */
export const LANGUAGE_NAMES: Record<DisplayLanguage, string> = { en: 'English', vi: 'Tiếng Việt' };
/** The locale for dates and numbers. */
export const LOCALES: Record<DisplayLanguage, string> = { en: 'en-US', vi: 'vi-VN' };

/** One message, placeholders filled. An unknown language falls back to English. */
export function translate(lang: string, key: MsgKey, vars: Record<string, string | number> = {}): string {
  const cat = (CATALOGS as Record<string, Record<MsgKey, string>>)[lang] ?? EN;
  return (cat[key] ?? EN[key]).replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
