#!/usr/bin/env node
// generate-permission-docs.mjs — BUILD_PLAN Phase 9 (Constitution 2 "metadata registry + generator").
//
//   node tooling/permissions/generate-permission-docs.mjs            write both outputs
//   node tooling/permissions/generate-permission-docs.mjs --check    exit 1 if either is stale (CI)
//
// Outputs
//   1. packages/permissions/src/permission-aliases.generated.ts — every legacy `pos.<domain>.<action>` key the backend
//      uses (on a route or in a service), which the registry folds in as deprecatedAliases of the catalog key the guard
//      maps it to. Rebuild packages/permissions after regenerating it.
//   2. docs/PERMISSIONS.md — the registry as a document: every key with label, sensitivity, scopes, step-up, the base
//      roles that hold it by default and its legacy aliases, grouped by realm and domain. Read from the BUILT registry
//      (packages/permissions/dist), so it is exactly what the API serves at GET /pos/access/catalog.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanKeyUsages, posAliasKeys } from './scan-permission-keys.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../..');
const ALIASES = join(REPO, 'packages/permissions/src/permission-aliases.generated.ts');
const DOC = join(REPO, 'docs/PERMISSIONS.md');
const check = process.argv.includes('--check');

export function aliasesSource(keys) {
  return `// permission-aliases.generated.ts — GENERATED by tooling/permissions/generate-permission-docs.mjs. Do not edit by hand.
// Every legacy \`pos.<domain>.<action>\` permission key the backend uses (route decorators + service checks). The registry
// folds each one into the catalog key requiredCapability() maps it to (deprecatedAliases). Regenerate after adding one.
export const POS_ROUTE_KEY_ALIASES: readonly string[] = [
${keys.map((k) => `  '${k}',`).join('\n')}
];
`;
}

export function docSource(reg, rolesHolding) {
  const by = new Map();
  for (const d of reg) { const k = `${d.realm}::${d.domain}`; if (!by.has(k)) by.set(k, []); by.get(k).push(d); }
  const realms = [['tenant', 'Salon (POS)'], ['owner', 'Owner App'], ['technician', 'Technician App'], ['platform', 'Platform (Super Admin)']];
  const count = (s) => reg.filter((d) => d.sensitivity === s).length;
  const out = [
    '# Permissions',
    '',
    '> GENERATED from `packages/permissions/src/permission-registry.ts` by `tooling/permissions/generate-permission-docs.mjs`. Do not edit by hand.',
    '',
    `${reg.length} catalog keys — critical ${count('critical')}, high ${count('high')}, medium ${count('medium')}, low ${count('low')}; ` +
      `${reg.filter((d) => d.stepUp).length} need a fresh step-up to grant or use; ${reg.reduce((s, d) => s + d.deprecatedAliases.length, 0)} legacy \`pos.*\` route keys folded in as aliases.`,
    '',
    'Authorization is by PERMISSION, never by role name: a role (or template / custom role) is a set of these keys; a per-person',
    'ALLOW / DENY override adds or removes one; DENY always wins. Scopes say where a key applies (OWN = the person\'s own records,',
    'BRANCH / SELECTED_BRANCHES = the branches they may enter, TENANT = every branch). High / critical keys are listed in the',
    'owner\'s high-risk report and in every access review.',
    '',
  ];
  for (const [realm, title] of realms) {
    const groups = [...by.entries()].filter(([k]) => k.startsWith(realm + '::'));
    if (!groups.length) continue;
    out.push(`## ${title}`, '');
    for (const [k, defs] of groups) {
      out.push(`### ${k.split('::')[1] || '(root)'}`, '', '| Key | Label | Sensitivity | Scopes | Step-up | Default roles | Description | Legacy aliases |', '|---|---|---|---|---|---|---|---|');
      for (const d of defs) {
        const roles = realm === 'platform' ? 'platform roles' : rolesHolding(d.key).join(', ') || '—';
        const esc = (s) => String(s).replace(/\|/g, '\\|');
        out.push(`| \`${d.key}\` | ${esc(d.label)} | ${d.sensitivity} | ${d.scopes.join(', ') || '—'} | ${d.stepUp ? 'yes' : ''} | ${roles} | ${esc(d.description)} | ${d.deprecatedAliases.map((a) => `\`${a}\``).join(' ')} |`);
      }
      out.push('');
    }
  }
  return out.join('\n');
}

const keys = posAliasKeys(scanKeyUsages(REPO));
const aliasesNow = aliasesSource(keys);
const stale = [];
if (!existsSync(ALIASES) || readFileSync(ALIASES, 'utf8') !== aliasesNow) {
  if (check) stale.push('packages/permissions/src/permission-aliases.generated.ts');
  else { writeFileSync(ALIASES, aliasesNow); console.log(`wrote ${keys.length} aliases → packages/permissions/src/permission-aliases.generated.ts (rebuild packages/permissions)`); }
}
const require = createRequire(import.meta.url);
const distReg = join(REPO, 'packages/permissions/dist/permission-registry.js');
if (existsSync(distReg)) {
  const { PERMISSION_REGISTRY, rolesHolding } = require(distReg);
  const doc = docSource(PERMISSION_REGISTRY, rolesHolding) + '\n';
  if (!existsSync(DOC) || readFileSync(DOC, 'utf8') !== doc) {
    if (check) stale.push('docs/PERMISSIONS.md');
    else { writeFileSync(DOC, doc); console.log(`wrote docs/PERMISSIONS.md (${PERMISSION_REGISTRY.length} keys)`); }
  }
} else {
  console.error('packages/permissions/dist/permission-registry.js not built — build packages/permissions first (npm run build -w @aipowersalon/permissions).');
  process.exit(2);
}
if (check) {
  if (stale.length) { console.error(`STALE: ${stale.join(', ')} — run node tooling/permissions/generate-permission-docs.mjs (and rebuild packages/permissions)`); process.exit(1); }
  console.log('permission docs + aliases up to date');
}
