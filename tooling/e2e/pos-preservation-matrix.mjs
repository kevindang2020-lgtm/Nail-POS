#!/usr/bin/env node
// pos-preservation-matrix.mjs — SUNMI FLEX 3 addenda "Required artifact: a preservation matrix" (Communications, Team,
// Technicians, Phone & Messaging, Earning Rules, Five Unfinished Features …): one row per registered module →
// route → component file that renders it → API client calls on that page → status → regression evidence.
//
// Generated from the module registry (apps/pos-web/src/shell/module-registry.json) and the screen sources, so it can
// never drift from what the registry gate (tooling/ci/check-pos-module-registry.mjs) and the browser screen check
// (tooling/e2e/pos-vi-one-screen.mjs) actually enforce. Status here is SOURCE status only: "present" = the id is in the
// rendered component tree. Browser visibility is proven by the screen-check run recorded in the handoff note, not here.
//   node tooling/e2e/pos-preservation-matrix.mjs [--out docs/handoff/SUNMI_PRESERVATION_MATRIX.md] [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(ROOT, 'apps/pos-web/src');
const REG = JSON.parse(readFileSync(join(SRC, 'shell/module-registry.json'), 'utf8'));
const args = process.argv.slice(2);
const outArg = args.indexOf('--out');
const OUT = join(ROOT, outArg >= 0 ? args[outArg + 1] : 'docs/handoff/SUNMI_PRESERVATION_MATRIX.md');
const check = args.includes('--check');

const resolveImport = (from, spec) => {
  const base = resolve(dirname(from), spec);
  for (const c of [base, base + '.tsx', base + '.ts', join(base, 'index.tsx'), join(base, 'index.ts')]) if (existsSync(c) && c.startsWith(SRC) && /\.tsx?$/.test(c)) return c;
  return null;
};
/** Same closure rule as the registry gate: the screen file + relative imports, depth 3, no tests / i18n. */
function closure(screen) {
  const start = join(SRC, 'screens', screen + '.tsx');
  if (!existsSync(start)) return [];
  const seen = new Set([start]); let frontier = [start];
  for (let d = 0; d < 3; d++) {
    const next = [];
    for (const f of frontier) for (const m of readFileSync(f, 'utf8').matchAll(/from\s+'(\.{1,2}\/[^']+)'/g)) {
      const r = resolveImport(f, m[1]);
      if (r && !seen.has(r) && !/\.test\.tsx?$/.test(r) && !r.includes('/i18n/')) { seen.add(r); next.push(r); }
    }
    frontier = next;
  }
  return [...seen];
}
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const idRe = (id) => new RegExp(`(?:data-module-id|data-testid|testId)=(?:\\{?\\s*)?["']${id.replace(/[-]/g, '\\-')}["']`);

const lines = [];
let rows = 0, missing = 0;
lines.push('# SUNMI preservation matrix (generated)', '',
  'Generated by `node tooling/e2e/pos-preservation-matrix.mjs` from the module registry and the screen sources — do not edit by hand.',
  'Status is **source** status (the module id is in the rendered component tree). Browser visibility at 1920×945 / 952 / 1032 in EN + VI is',
  'proven by `tooling/e2e/pos-vi-one-screen.mjs` (see the SUNMI batch handoff notes). Unknown is reported as NOT VERIFIED, never "complete".', '');
lines.push(`Pages: ${REG.pages.length} · modules: ${REG.pages.reduce((n, p) => n + p.modules.length, 0)}`, '');

for (const p of REG.pages) {
  const files = p.screens.flatMap(closure);
  const srcs = new Map(files.map((f) => [f, readFileSync(f, 'utf8')]));
  const apis = new Set();
  for (const s of srcs.values()) for (const m of s.matchAll(/\b(pos\w*Api|\w+Api)\.(\w+)\(/g)) if (!/^(React|use)/.test(m[1])) apis.add(`${m[1]}.${m[2]}`);
  lines.push(`## ${esc(p.title)} — \`${p.key}\``, '',
    `- Route: ${p.routes.map((r) => '`' + r + '`').join(', ')}`,
    `- Screen: ${p.screens.map((s) => '`screens/' + s + '.tsx`').join(', ')}`,
    `- Guide: ${esc(p.guide ?? 'NOT RECORDED')}`,
    `- Scroll: ${p.scroll === 'page' ? 'vertical page scroll allowed (' + esc(p.scrollReason ?? 'addendum') + ')' : 'one screen'}`,
    `- API calls on this page: ${apis.size ? [...apis].sort().map((a) => '`' + a + '`').join(', ') : 'NOT VERIFIED (no typed API client call found in the component tree)'}`, '',
    '| Module (original feature) | id | Component file | Status | Regression evidence |', '|---|---|---|---|---|');
  for (const m of p.modules) {
    rows++;
    const hit = [...srcs].find(([, s]) => idRe(m.id).test(s));
    if (!hit) missing++;
    const count = m.minItems ? ` (≥ ${m.minItems} items)` : '';
    lines.push(`| ${esc(m.label)}${count} | \`${m.id}\` | ${hit ? '`' + relative(SRC, hit[0]) + '`' : '—'} | ${hit ? 'present' : '**MISSING**'} | registry gate + screen check \`${p.key}\` |`);
  }
  lines.push('');
}
const text = lines.join('\n') + '\n';
if (check) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error(`preservation matrix is stale — run: node tooling/e2e/pos-preservation-matrix.mjs`); process.exit(1); }
  console.log(`preservation matrix current — ${rows} rows`); process.exit(missing ? 1 : 0);
}
writeFileSync(OUT, text);
console.log(`preservation matrix written: ${relative(ROOT, OUT)} — ${REG.pages.length} pages, ${rows} rows, ${missing} missing`);
if (missing) process.exit(1);
