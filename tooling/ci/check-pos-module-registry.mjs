#!/usr/bin/env node
// check-pos-module-registry.mjs — SUNMI FLEX 3 mandates (Nov 6 2026): the "Module Preservation Registry" and "Release
// Quality Gate" (Full-System addendum recommendations 3 + 12; every page addendum's "no module may disappear" rule).
//
// Two checks over apps/pos-web/src/shell/module-registry.json:
//   1. REGISTRY — every registered page names screens that exist and has at least one module, and every registered module
//      id is still in that screen's source (data-module-id / data-testid / testId literal, in the screen file or a file it
//      imports relatively, three levels deep). A refactor that drops a registered module fails here.
//   2. BASELINE — tooling/ci/pos-module-baseline.json records every module-style id (data-module-id, data-testid, testId)
//      each registered page's source carried when it was last reviewed. An id that disappears fails (the inventory shrank);
//      a new id is reported and accepted with --update. Removing one on purpose = editing the baseline in the same commit,
//      which is visible in review.
// The browser half (every registered module VISIBLE inside the viewport at the certified profiles) is in
// tooling/e2e/pos-vi-one-screen.mjs; the in-app half is the Screen Check overlay (shell/ScreenCheckDialog.tsx).
//   node tooling/ci/check-pos-module-registry.mjs [--update]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(ROOT, 'apps/pos-web/src');
const REG = JSON.parse(readFileSync(join(SRC, 'shell/module-registry.json'), 'utf8'));
const BASE_FILE = join(ROOT, 'tooling/ci/pos-module-baseline.json');
const update = process.argv.includes('--update');

const resolveImport = (from, spec) => {
  const base = resolve(dirname(from), spec);
  for (const c of [base, base + '.tsx', base + '.ts', join(base, 'index.tsx'), join(base, 'index.ts')]) if (existsSync(c) && c.startsWith(SRC) && /\.tsx?$/.test(c)) return c;
  return null;
};
/** The screen file + the files it imports relatively (depth 3), excluding tests. */
export function closure(screen) {
  const start = join(SRC, 'screens', screen + '.tsx');
  if (!existsSync(start)) return null;
  const seen = new Set([start]); let frontier = [start];
  for (let d = 0; d < 3; d++) {
    const next = [];
    for (const f of frontier) {
      const src = readFileSync(f, 'utf8');
      for (const m of src.matchAll(/from\s+'(\.{1,2}\/[^']+)'/g)) {
        const r = resolveImport(f, m[1]);
        if (r && !seen.has(r) && !/\.test\.tsx?$/.test(r) && !r.includes('/i18n/')) { seen.add(r); next.push(r); }
      }
    }
    frontier = next;
  }
  return [...seen];
}
const ID_RE = /(?:data-module-id|data-testid|testId)=(?:\{?\s*)?["']([a-z0-9][a-z0-9_-]*)["']/g;
export function idsIn(files) {
  const ids = new Set();
  for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(ID_RE)) ids.add(m[1]);
  return ids;
}

const failures = [], notes = [];
const baseline = existsSync(BASE_FILE) ? JSON.parse(readFileSync(BASE_FILE, 'utf8')) : { pages: {} };
const nextBaseline = { $comment: 'Generated by tooling/ci/check-pos-module-registry.mjs --update. Every module-style id each registered POS page carried when last reviewed; an id may only disappear in a commit that edits this file (reviewed).', pages: {} };
for (const p of REG.pages) {
  const files = [];
  for (const s of p.screens) { const c = closure(s); if (!c) failures.push(`${p.key}: screen ${s}.tsx does not exist`); else files.push(...c); }
  if (!files.length) continue;
  if (!p.modules?.length) failures.push(`${p.key}: no registered modules (every SUNMI page lists its modules)`);
  const ids = idsIn([...new Set(files)]);
  for (const m of p.modules ?? []) if (!ids.has(m.id)) failures.push(`${p.key}: registered module "${m.id}" (${m.label}) is no longer in ${p.screens.join(' / ')}`);
  const sorted = [...ids].sort();
  nextBaseline.pages[p.key] = sorted;
  const before = baseline.pages?.[p.key];
  if (before) {
    const gone = before.filter((id) => !ids.has(id));
    const added = sorted.filter((id) => !before.includes(id));
    if (gone.length) failures.push(`${p.key}: ${gone.length} module id(s) disappeared since the reviewed baseline: ${gone.slice(0, 12).join(', ')}${gone.length > 12 ? ' …' : ''}`);
    if (added.length) notes.push(`${p.key}: ${added.length} new id(s) — accept with --update`);
  } else notes.push(`${p.key}: no baseline yet — create it with --update`);
}
if (update) {
  // --update records growth; it never hides a disappearance unless the reviewer passes --accept-removals
  if (failures.some((f) => f.includes('disappeared')) && !process.argv.includes('--accept-removals')) { console.error(failures.join('\n')); console.error('\nrefusing to update: ids disappeared (pass --accept-removals after review)'); process.exit(1); }
  writeFileSync(BASE_FILE, JSON.stringify(nextBaseline, null, 1) + '\n');
  console.log(`pos module baseline written: ${Object.keys(nextBaseline.pages).length} pages`);
}
for (const n of notes) console.log('note:', n);
if (failures.length && !update) { console.error(failures.map((f) => 'FAIL ' + f).join('\n')); process.exit(1); }
const total = REG.pages.reduce((n, p) => n + (p.modules?.length ?? 0), 0);
if (!update) console.log(`pos module registry OK — ${REG.pages.length} pages, ${total} registered modules present in source, baseline intact`);
