#!/usr/bin/env node
// vi-drafts.mjs — Kevin reviews every Vietnamese POS string himself; new VI text ships marked `// DRAFT — Kevin reviews`.
// This tool turns that marker into a review sheet he can read on an iPad, and applies his answers back to the source.
//
//   node tooling/i18n/vi-drafts.mjs                       write docs/handoff/VI_DRAFT_REVIEW.md (EN | VI | where used)
//   node tooling/i18n/vi-drafts.mjs --approve all         Kevin approved everything: drop every DRAFT marker
//   node tooling/i18n/vi-drafts.mjs --approve 3,7,12      approve by row number from the sheet
//   node tooling/i18n/vi-drafts.mjs --approve 'bv.hd.*'   approve by key or key prefix
//   node tooling/i18n/vi-drafts.mjs --set 5 'Văn bản mới' Kevin's correction for row 5 (also approves it)
//   node tooling/i18n/vi-drafts.mjs --check               fail if the sheet is stale (gate)
//
// Row numbers shift after an approval: apply --set corrections first, then --approve.
// Only the marker and (for --set) the quoted value change; keys, order and every other line stay byte-identical.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(ROOT, 'apps/pos-web/src');
const I18N = join(SRC, 'i18n');
const SHEET = join(ROOT, 'docs/handoff/VI_DRAFT_REVIEW.md');
const MARK = /\s*\/\/\s*DRAFT\b[^\n]*$/;
const LINE = /^(\s*)(['"])([^'"]+)\2(\s*:\s*)(['"])((?:\\.|(?!\5).)*)\5(,?)(.*)$/;

const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const viFiles = walk(I18N).filter((f) => f.endsWith('.vi.ts')).sort();
const enFiles = walk(I18N).filter((f) => f.endsWith('.en.ts'));

const enValue = new Map();
for (const f of enFiles) for (const l of readFileSync(f, 'utf8').split('\n')) { const m = l.match(LINE); if (m && !enValue.has(m[3])) enValue.set(m[3], m[6]); }

/** Every DRAFT row, in file order — row numbers are stable for one version of the sources. */
function scan() {
  const rows = [];
  for (const f of viFiles) {
    readFileSync(f, 'utf8').split('\n').forEach((l, i) => {
      if (!MARK.test(l)) return;
      const m = l.replace(MARK, '').match(LINE);
      if (m) rows.push({ n: rows.length + 1, file: f, line: i, key: m[3], vi: m[6], en: enValue.get(m[3]) ?? '(no English entry)', note: (l.match(MARK)[0].match(/\(([^)]*)\)/) || [])[1] ?? '' });
    });
  }
  return rows;
}

let codeFiles = null;
function usedIn(key) {
  codeFiles ??= walk(SRC).filter((f) => /\.tsx?$/.test(f) && !f.includes('/i18n/') && !/\.test\.tsx?$/.test(f)).map((f) => [f, readFileSync(f, 'utf8')]);
  const prefix = key.replace(/\.[^.]+$/, '.');
  const hit = codeFiles.find(([, s]) => s.includes(`'${key}'`) || s.includes(`"${key}"`)) ?? codeFiles.find(([, s]) => s.includes(`'${prefix}`) || s.includes(`\`${prefix}`));
  return hit ? relative(SRC, hit[0]) : '—';
}

const cell = (s) => String(s).replace(/\\(['"])/g, '$1').replace(/\|/g, '\\|');
function sheet(rows) {
  const out = ['# Vietnamese DRAFT strings — Kevin review sheet (generated)', '',
    'Generated by `node tooling/i18n/vi-drafts.mjs`. Reply with any of:', '',
    '- **"approve all"** — every row is fine.', '- **"approve 1-20, 25"** — those rows are fine.',
    '- **"row 7: <Vietnamese>"** — use your wording for row 7.', '',
    `Rows: ${rows.length} · files: ${new Set(rows.map((r) => r.file)).size}`, ''];
  let file = '';
  for (const r of rows) {
    if (r.file !== file) { file = r.file; out.push('', `## ${relative(SRC, file)}`, '', '| # | Key | English | Vietnamese (DRAFT) | Used in |', '|---|---|---|---|---|'); }
    out.push(`| ${r.n} | \`${r.key}\` | ${cell(r.en)} | ${cell(r.vi)}${r.note ? ` _(${cell(r.note)})_` : ''} | ${usedIn(r.key)} |`);
  }
  return out.join('\n') + '\n';
}

function pick(rows, spec) {
  if (spec === 'all') return rows;
  const want = new Set();
  for (const part of spec.split(',').map((s) => s.trim()).filter(Boolean)) {
    const range = part.match(/^(\d+)-(\d+)$/);
    if (range) { for (let i = +range[1]; i <= +range[2]; i++) want.add(i); continue; }
    if (/^\d+$/.test(part)) { want.add(+part); continue; }
    const re = part.endsWith('*') ? (k) => k.startsWith(part.slice(0, -1)) : (k) => k === part;
    rows.filter((r) => re(r.key)).forEach((r) => want.add(r.n));
  }
  const got = rows.filter((r) => want.has(r.n));
  if (!got.length) { console.error(`nothing matched "${spec}"`); process.exit(2); }
  return got;
}

function apply(edits) {   // edits: [{ row, value? }]
  const byFile = new Map();
  for (const e of edits) (byFile.get(e.row.file) ?? byFile.set(e.row.file, []).get(e.row.file)).push(e);
  for (const [f, es] of byFile) {
    const lines = readFileSync(f, 'utf8').split('\n');
    for (const { row, value } of es) {
      let l = lines[row.line].replace(MARK, '');
      if (value != null) {
        const m = l.match(LINE);
        const q = m[5];
        const v = value.replace(/\\/g, '\\\\').replace(new RegExp(q, 'g'), '\\' + q);
        l = `${m[1]}${m[2]}${m[3]}${m[2]}${m[4]}${q}${v}${q}${m[7]}${m[8]}`;
      }
      lines[row.line] = l;
    }
    writeFileSync(f, lines.join('\n'));
  }
}

const args = process.argv.slice(2);
const rows = scan();
if (args[0] === '--approve') {
  const got = pick(rows, args[1] ?? '');
  apply(got.map((row) => ({ row })));
  console.log(`approved ${got.length} row(s); DRAFT markers removed`);
  writeFileSync(SHEET, sheet(scan()));
} else if (args[0] === '--set') {
  const row = rows.find((r) => r.n === +args[1]);
  if (!row || args[2] == null) { console.error('usage: --set <row> <vietnamese>'); process.exit(2); }
  apply([{ row, value: args[2] }]);
  console.log(`row ${row.n} (${row.key}) set and approved`);
  writeFileSync(SHEET, sheet(scan()));
} else if (args[0] === '--check') {
  const want = sheet(rows);
  if (!existsSync(SHEET) || readFileSync(SHEET, 'utf8') !== want) { console.error('VI draft review sheet is stale — run: node tooling/i18n/vi-drafts.mjs'); process.exit(1); }
  console.log(`VI draft review sheet current — ${rows.length} row(s) waiting for Kevin`);
} else {
  writeFileSync(SHEET, sheet(rows));
  console.log(`VI draft review sheet written: ${relative(ROOT, SHEET)} — ${rows.length} rows`);
}
